def _required_constants() -> dict[str, Any]:
    """The ``config`` thresholds the copied sources close over.

    Found by reading the sources rather than listed here: a hand-kept list goes stale
    the first time one of those functions starts using a different threshold, and the
    failure is a ``NameError`` in the user's script rather than anything visible here.
    """
    import re

    from app import config

    sources = "\n".join(
        textwrap.dedent(inspect.getsource(obj)) for _origin, obj in _COPIED
    )
    return {
        name: getattr(config, name)
        for name in dir(config)
        if name.isupper() and re.search(rf"\b{name}\b", sources)
    }


def _copied_source() -> str:
    """The engine's own definitions, in dependency order, as text."""
    chunks: list[str] = []
    constants = _required_constants()
    if constants:
        chunks.append(
            "# --- thresholds these definitions use, from app.config "
            + "-" * 14
            + "\n\n"
            + "\n".join(f"{name} = {value!r}" for name, value in sorted(constants.items()))
        )
    for origin, obj in _COPIED:
        source = textwrap.dedent(inspect.getsource(obj))
        chunks.append(f"# --- from app.{origin}: {obj.__name__} " + "-" * 30 + "\n\n" + source)
    # `output_hash` closes the loop: the script reports the same digest the run did, so
    # "this reproduces that run" is checkable by comparing one string.
    chunks.append(
        "# --- from app.runner: output_hash " + "-" * 30 + "\n\nimport hashlib\n\n"
        + textwrap.dedent(inspect.getsource(runner.output_hash))
    )
    return "\n\n".join(chunks)


def generate_from_plan(
    plan: PreprocessingPlan,
    source: SourceFormat | None = None,
    run_id: str = "(unsaved)",
    numeric_columns: list[str] | None = None,
    date_columns: list[str] | None = None,
    missing_tokens: list[str] | None = None,
) -> str:
    """Emit the complete program that reproduces one run of ``plan``.

    Args:
        plan: the decisions to carry out. Serialised into the file as data.
        source: how to read the input file, as ingestion detected it. Omitting it
            assumes a comma-separated UTF-8 file, which is right only for that case.
        run_id: named in the docstring so a script found later can be traced back.
        numeric_columns / date_columns / missing_tokens: the repairs ingestion applied,
            repeated here so the script rebuilds the same frame from the original bytes.
    """
    from app.services.ingest import MISSING_TOKENS

    source = source or SourceFormat()
    body = _BODY.format(
        read_call=source.read_expression(),
        missing_tokens=sorted(missing_tokens or MISSING_TOKENS),
        numeric_columns=list(numeric_columns or []),
        date_columns=list(date_columns or []),
    )
    return (
        GENERATED_FROM_PLAN_HEADER
        + "\n"
        + _PREAMBLE.format(
            run_id=run_id,
            plan_json=json.dumps(plan.model_dump(mode="json"), indent=2),
        )
        + _ENGINE_HEADER
        + "\n"
        + _copied_source()
        + "\n"
        + body
    )
