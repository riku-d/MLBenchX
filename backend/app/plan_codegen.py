"""Generate a standalone script that reproduces a run, from the plan that drove it.

There are two artefacts here and they are not the same thing: the **runtime engine**
(:mod:`app.runner`) fits an sklearn pipeline in this process, and the **generated
script** is Python a user reads, edits and runs for themselves. Keeping both is a
product decision — the editor is the reason the code exists — but keeping two
*implementations* of the transformation rules is how the two drift, and an audit of this
repository found exactly that: a decision taken over the whole file in one path and over
the training fold in the other, invisible because the other path was correct.

So this module does not reimplement anything. It emits:

* the plan, as a JSON literal — the canonical representation both paths consume;
* the project's own transformer classes and pipeline builder, **copied verbatim** from
  :mod:`app.runner` and :mod:`app.services.glassbox` with :func:`inspect.getsource`;
* the preparation and split rules, likewise copied.

The generated file therefore contains the same code the engine runs, which is a stronger
guarantee than a test could give: the two cannot disagree about what one-hot encoding
means, because there is one definition of it and the script has a copy. What the script
adds is the part a user wants to change — which file is read, which columns are kept,
what happens to each one — expressed as data at the top where it can be edited.

The cost of that choice is honest and worth stating: the file is longer than a
hand-written equivalent, because it carries the real implementations rather than a
simplified retelling of them. A shorter script that quietly did something slightly
different would be worse.
"""

