"""Turn a :class:`~app.pipeline.PipelineConfig` into Python the user can read and run.

This module is the only place pipeline configuration becomes code. That matters more
than it sounds: if two places generated code, the editor would eventually show one thing
and the executor run another, and the product's central claim — that you can see exactly
what is happening to your data — would quietly stop being true.

What the generated script is
----------------------------
A standalone program, not a fragment. It imports what it needs, reads a CSV, applies the
enabled steps in :data:`~app.pipeline.STEP_ORDER`, writes the result, and exits. It runs
on any machine with pandas and scikit-learn — including the user's, after they download
it — with no reference to this application.

Readability is a functional requirement here, not a courtesy. The user is expected to
open this file, understand it, and change it. So the generated code:

* says *why* in a comment above each step, in the same words the UI card uses;
* keeps the train/test split before every ``fit``, and says so at the line where it
  happens;
* uses ordinary pandas and sklearn idioms rather than clever ones;
* never emits a step that is switched off — a commented-out block is clutter that the
  reader has to evaluate and discard.

The reporting contract
----------------------
The script writes a JSON report alongside its output, recording the shape of the data
before and after each step. The workspace reads it to fill the step cards and the health
panel. A user who edits the code is free to delete the reporting calls; the app falls
back to comparing the input and output files, so it can still show what changed overall,
just not step by step. That degradation is deliberate — the alternative is refusing to
run code the user wrote, which would make the editor decorative.
"""

