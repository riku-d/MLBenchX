def _scaler_class(method: str) -> str:
    return {"standard": "StandardScaler", "minmax": "MinMaxScaler", "robust": "RobustScaler"}[
        method
    ]


def _sklearn_imports(config: PipelineConfig) -> str:
    """Import only what this configuration actually uses.

    A generated file is meant to be read. Importing six transformers when the pipeline
    uses one makes the reader wonder which of them matter, and makes "this step is
    switched off" less than completely true — the name would still be there in the
    imports.
    """
    impute: list[str] = []
    preprocessing: list[str] = []

    if config.missing_values.enabled and config.missing_values.numeric_strategy in (
        "median", "mean", "constant",
    ):
        impute.append("SimpleImputer")
    if config.missing_values.enabled and config.missing_values.categorical_strategy in (
        "most_frequent", "constant",
    ):
        impute.append("SimpleImputer")

    if config.encoding.enabled:
        methods = {
            config.encoding.binary_method,
            config.encoding.low_cardinality_method,
            config.encoding.high_cardinality_method,
        }
        if "onehot" in methods:
            preprocessing.append("OneHotEncoder")
        if methods & {"label", "ordinal"}:
            preprocessing.append("OrdinalEncoder")
        if "target" in methods:
            preprocessing.append("TargetEncoder")

    if config.scaling.enabled:
        preprocessing.append(_scaler_class(config.scaling.method))

    lines: list[str] = []
    if impute:
        lines.append(f"from sklearn.impute import {', '.join(sorted(set(impute)))}")
    if preprocessing:
        lines.append(
            f"from sklearn.preprocessing import {', '.join(sorted(set(preprocessing)))}"
        )
    return "\n".join(lines) + ("\n" if lines else "")


def generate(config: PipelineConfig) -> str:
    """Emit the complete Python program for one pipeline configuration.

    Steps that are switched off contribute nothing — not a commented-out block, which
    the reader would have to evaluate and dismiss. The file is what will run.
    """
    parts: list[str] = [
        _PREAMBLE.format(
            target=config.target,
            test_size=config.test_size,
            seed=config.seed,
            sklearn_imports=_sklearn_imports(config),
            extra_imports="",
        )
    ]

    # --- always on: the rest of the pipeline is meaningless without column kinds ----
    parts.append(_DATA_TYPES.format())
    if config.data_types.coerce_numeric:
        parts.append(_COERCE_NUMERIC)
    if config.data_types.parse_dates:
        parts.append(_PARSE_DATES.format())
    parts.append(_TYPES_FOOTER.format())

    if config.excluded_columns:
        parts.append(_EXCLUDE.format(excluded=config.excluded_columns))

    if config.data_types.parse_dates:
        parts.append(_DATETIME_FEATURES.format())

    if config.duplicates.enabled:
        parts.append(
            _DUPLICATES.format(
                subset=config.duplicates.subset, keep=config.duplicates.keep
            )
        )

    # Column removal has to precede the split: dropping a column changes nothing about
    # which rows are held out, and doing it first keeps the split code simple.
    if config.missing_values.enabled:
        parts.append(
            _MISSING_DROP_COLUMNS.format(
                threshold=config.missing_values.drop_column_threshold
            )
        )

    parts.append(_SPLIT.format())

    if config.missing_values.enabled:
        parts.append(_MISSING_IMPUTE)
        parts.append(_numeric_imputation(config))
        parts.append(_categorical_imputation(config))
        parts.append(_MISSING_FOOTER.format())

    if config.outliers.enabled:
        parts.append(_outlier_block(config))

    if config.encoding.enabled:
        parts.append(
            _ENCODING.format(
                max_onehot=config.encoding.max_onehot_cardinality,
                binary_method=config.encoding.binary_method,
                low_method=config.encoding.low_cardinality_method,
                high_method=config.encoding.high_cardinality_method,
                handle_unknown=config.encoding.handle_unknown,
            )
        )

    if config.scaling.enabled:
        parts.append(
            _SCALING.format(
                columns=config.scaling.columns,
                scaler=_scaler_class(config.scaling.method),
            )
        )

    if config.feature_selection.enabled:
        parts.append(_feature_selection_block(config))

    if config.imbalance.enabled:
        block = _IMBALANCE_REPORT.format(threshold=config.imbalance.ratio_threshold)
        if config.imbalance.action in ("oversample", "undersample"):
            block += _IMBALANCE_RESAMPLE.format(
                oversample=config.imbalance.action == "oversample"
            )
        parts.append(block)

    parts.append(_FOOTER)
    return "".join(parts)


def _numeric_imputation(config: PipelineConfig) -> str:
    strategy = config.missing_values.numeric_strategy
    if strategy in ("median", "mean"):
        return _MISSING_NUMERIC_SIMPLE.format(strategy=strategy, fill_kwarg="")
    if strategy == "constant":
        return _MISSING_NUMERIC_SIMPLE.format(
            strategy="constant",
            fill_kwarg=f", fill_value={config.missing_values.numeric_fill_value!r}",
        )
    if strategy in ("forward_fill", "backward_fill"):
        return _MISSING_NUMERIC_FILL.format(
            method="ffill" if strategy == "forward_fill" else "bfill"
        )
    return _MISSING_NUMERIC_DROP.format()


def _categorical_imputation(config: PipelineConfig) -> str:
    strategy = config.missing_values.categorical_strategy
    if strategy == "most_frequent":
        return _MISSING_CATEGORICAL_SIMPLE.format(strategy="most_frequent", fill_kwarg="")
    if strategy == "constant":
        return _MISSING_CATEGORICAL_SIMPLE.format(
            strategy="constant",
            fill_kwarg=f", fill_value={config.missing_values.categorical_fill_value!r}",
        )
    if strategy in ("forward_fill", "backward_fill"):
        return _MISSING_CATEGORICAL_FILL.format(
            method="ffill" if strategy == "forward_fill" else "bfill"
        )
    return _MISSING_CATEGORICAL_DROP.format()


def _outlier_block(config: PipelineConfig) -> str:
    step = config.outliers
    bounds = (
        _BOUNDS_IQR.format(multiplier=step.iqr_multiplier)
        if step.method == "iqr"
        else _BOUNDS_ZSCORE.format(threshold=step.zscore_threshold)
    )
    action, word = {
        "cap": (_ACTION_CAP, "capped"),
        "remove": (_ACTION_REMOVE, "removed rows holding"),
        "winsorize": (_ACTION_WINSORIZE.format(quantile=step.winsorize_quantile), "winsorized"),
        "flag": (_ACTION_FLAG, "flagged"),
    }[step.action]
    return _OUTLIERS.format(
        columns=step.columns, bounds=bounds, action=action, action_word=word
    )


def _feature_selection_block(config: PipelineConfig) -> str:
    step = config.feature_selection
    block = _FEATURE_SELECTION
    if step.variance_threshold is not None:
        block += _FS_VARIANCE.format(threshold=step.variance_threshold)
    if step.correlation_threshold is not None:
        block += _FS_CORRELATION.format(threshold=step.correlation_threshold)
    if step.mutual_information and step.top_k:
        block += _FS_MUTUAL_INFO.format(top_k=step.top_k)
    return block + _FS_FOOTER.format()


def explain_step(step_id: str, config: PipelineConfig) -> str:
    """The sentence shown on a step's card, reflecting how it is configured.

    Kept beside the generator so a new option cannot be added to the code without the
    explanation for it being visibly absent here.
    """
    if step_id == "missing_values":
        step = config.missing_values
        names = {
            "median": "the middle value",
            "mean": "the average",
            "constant": f"the fixed value {step.numeric_fill_value}",
            "forward_fill": "the previous row's value",
            "backward_fill": "the next row's value",
            "drop_rows": "nothing — rows with blanks are removed",
        }
        return (
            f"Numeric gaps are filled with {names[step.numeric_strategy]}; category gaps "
            f"with the most common value. Columns over "
            f"{step.drop_column_threshold:.0%} empty are dropped instead."
        )
    if step_id == "duplicates":
        scope = (
            "whole rows"
            if not config.duplicates.subset
            else f"the columns {', '.join(config.duplicates.subset)}"
        )
        return f"Rows that repeat another exactly, compared across {scope}."
    if step_id == "outliers":
        step = config.outliers
        method = (
            f"{step.iqr_multiplier}× the interquartile range"
            if step.method == "iqr"
            else f"{step.zscore_threshold} standard deviations"
        )
        actions = {
            "cap": "pulled back to the boundary",
            "remove": "their rows removed",
            "winsorize": "pulled to the nearest percentile",
            "flag": "marked in a new column, values untouched",
        }
        return f"Values beyond {method} are {actions[step.action]}."
    if step_id == "encoding":
        step = config.encoding
        return (
            f"Two-value columns use {step.binary_method}; up to "
            f"{step.max_onehot_cardinality} distinct values use "
            f"{step.low_cardinality_method}; above that, {step.high_cardinality_method}."
        )
    if step_id == "scaling":
        names = {
            "standard": "centred on the mean, divided by the spread",
            "minmax": "squeezed into the range 0 to 1",
            "robust": "centred on the median, divided by the interquartile range",
        }
        return f"Every numeric column is {names[config.scaling.method]}."
    if step_id == "feature_selection":
        step = config.feature_selection
        clauses = []
        if step.variance_threshold is not None:
            clauses.append(f"variance at or below {step.variance_threshold}")
        if step.correlation_threshold is not None:
            clauses.append(f"correlation at or above {step.correlation_threshold}")
        if step.mutual_information and step.top_k:
            clauses.append(f"outside the top {step.top_k} by mutual information")
        return "Columns are removed when they have " + ", or ".join(clauses) + "."
    if step_id == "imbalance":
        actions = {
            "report": "Reported only — no rows are changed.",
            "oversample": "The smaller classes are sampled up, in the training rows only.",
            "undersample": "The larger classes are sampled down, in the training rows only.",
            "class_weight": "Reported, with class weights suggested for your model.",
        }
        return actions[config.imbalance.action]
    if step_id == "data_types":
        parts = []
        if config.data_types.coerce_numeric:
            parts.append("numbers stored as text")
        if config.data_types.parse_dates:
            parts.append("dates stored as text")
        detected = " and ".join(parts) if parts else "nothing extra"
        return f"Column kinds are detected, including {detected}."
    return ""


def preview(config: PipelineConfig, max_lines: int = 40) -> str:
    """The first lines of the generated file, for a compact preview."""
    lines = generate(config).splitlines()
    body = [line for line in lines if line.strip() and not line.startswith('"""')]
    return textwrap.dedent("\n".join(body[:max_lines]))
